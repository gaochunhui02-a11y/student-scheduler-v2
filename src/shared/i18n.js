export const SUPPORTED_LANGUAGES = ['en', 'zh', 'ja'];
const dictionaries = { en, zh, ja };

export function getLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && dictionaries[stored]) return stored;
  } catch {
    // localStorage unavailable (e.g. a strict privacy mode) — fall back to English
  }
  return 'en';
}

// BCP-47 locale for the app's own language selector, for every
// toLocaleDateString/toLocaleTimeString call in the app — passing `undefined`
// there uses the BROWSER/OS locale instead, which silently disagrees with
// #langSelect (Checkpoint C.1 fix: the Planner heading showed Chinese date
// formatting while the language selector was set to English).
const LOCALE_BY_LANGUAGE = { en: 'en-US', zh: 'zh-CN', ja: 'ja-JP' };
export function getLocale() {
  return LOCALE_BY_LANGUAGE[getLanguage()] || 'en-US';
}

export function setLanguage(lang) {
  if (!dictionaries[lang]) return;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // per-viewer convenience only — fine if it can't persist
  }
}

export function t(key) {
  const lang = getLanguage();
  return (dictionaries[lang] && dictionaries[lang][key]) || dictionaries.en[key] || key;
}

// V2-G: translates a message object from a pure model — { error, errorKey,
// errorParams } (validation results) or { key, params } (scheduler notes).
// Falls back to the model's own English text when there's no key. Params
// fill {name}-style placeholders; a `list` param of {name, minutes} items
// is rendered with the translated "{name} ({minutes} min short)" pattern.
export function tMessage(msg) {
  if (!msg) return '';
  const key = msg.errorKey || msg.key;
  const params = msg.errorParams || msg.params || {};
  if (!key || !dictionaries.en[key]) return msg.error || '';
  let text = t(key);
  Object.entries(params).forEach(([name, value]) => {
    const rendered = Array.isArray(value)
      ? value.map((v) => t('schedulerMsg.shortItem').replace('{name}', v.name).replace('{minutes}', String(v.minutes))).join(t('schedulerMsg.listSeparator'))
      : String(value);
    text = text.split(`{${name}}`).join(rendered);
  });
  return text;
}

// Count-aware lookup (V2-G): when n === 1 and the CURRENT language defines
// `${key}One`, that singular form is used ("1 class", not "1 classes").
// Only English defines *One keys — Chinese and Japanese don't inflect for
// number, so they always use the base key. {count} and {n} are filled in.
export function tCount(key, n) {
  const lang = getLanguage();
  const dict = dictionaries[lang] || dictionaries.en;
  const text = n === 1 && dict[`${key}One`] ? dict[`${key}One`] : t(key);
  return text.replace('{count}', String(n)).replace('{n}', String(n));
}

// Sets .textContent (never .innerHTML) on every element with [data-i18n]
// under `root`. Because it only ever assigns textContent to the exact
// element carrying the attribute, it can never remove a nested functional
// child or id — the HTML is written so translatable text and functional
// sub-elements are always siblings, never parent/child of a translated node.
//
// [data-i18n-placeholder], [data-i18n-aria-label], and [data-i18n-title]
// additionally translate the `placeholder`, `aria-label`, and `title`
// attributes (Phase 3/4, for the Board's controls, including the SVG edge
// hit-lines and the node connection handle) — attribute-only, so these
// never touch an element's children either.
//
// Called on every language switch, so it re-sweeps the whole document,
// including Board nodes/edges rendered after the page loaded (they carry
// the same data-i18n* attributes at render time — see src/board/board.js).
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  document.documentElement.lang = getLanguage();
}
